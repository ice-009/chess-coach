// Service worker for the hosted build: saves the app (pages, code, Stockfish, SQLite) on the device so it keeps
// working with no connection, e.g. on a flight. Puzzles and chess.com data are kept as they are used.
// The file list is only known after the build, so sw.js is written into the output folder at the end.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

function walk(dir: string, base = dir): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full, base) : [path.relative(base, full).split(path.sep).join('/')];
  });
}

const source = (version: string, precache: string[]) => `// Generated by server/offlineSw.ts at build time.
const SHELL = 'cc-shell-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('cc-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms));

/**
 * Fresh when the network answers in time; on slow or flaky Wi-Fi the saved copy (while the network keeps
 * refreshing it in the background); with nothing saved yet, keep waiting for the network.
 */
async function networkFirst(cacheName, request, key, ms) {
  const cache = await caches.open(cacheName);
  const net = fetch(request).then(async (res) => {
    if (res.ok) await cache.put(key, res.clone());
    return res;
  });
  try {
    return await Promise.race([net, timeout(ms)]);
  } catch {
    const hit = await cache.match(key, { ignoreSearch: key === '/' });
    return hit || net;
  }
}

async function cacheFirst(cacheName, request) {
  const hit = await caches.match(request);
  if (hit) return hit;
  const res = await fetch(request);
  if (res.ok) await (await caches.open(cacheName)).put(request, res.clone());
  return res;
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (url.pathname === '/sw.js' || url.pathname.startsWith('/api/')) return; // accounts: always the network
    // the app is one page (hash routes), so every navigation is the start page
    if (req.mode === 'navigate') return event.respondWith(networkFirst(SHELL, req, '/', 4000));
    if (url.pathname === '/puzzles/manifest.json') return event.respondWith(networkFirst('cc-puzzles', req, req, 4000));
    if (url.pathname.startsWith('/puzzles/')) return event.respondWith(cacheFirst('cc-puzzles', req));
    return event.respondWith(cacheFirst(SHELL, req));
  }
  // your chess.com games and profile: the latest when online, the last copy you saw when offline
  if (url.hostname === 'api.chess.com') event.respondWith(networkFirst('cc-chesscom', req, req, 8000));
});
`;

export function offlineSw(enabled: boolean): Plugin {
  let outDir = '';
  return {
    name: 'chess-coach-offline-sw',
    apply: 'build',
    configResolved: (config) => void (outDir = path.resolve(config.root, config.build.outDir)),
    closeBundle() {
      if (!enabled) return;
      const files = walk(outDir).filter((f) => !f.startsWith('puzzles/') && !f.endsWith('.map') && !['sw.js', 'index.html', 'vercel.json'].includes(f));
      // the version changes whenever any saved file does, so devices pick up new builds
      const hash = createHash('sha256');
      for (const f of ['index.html', ...files]) hash.update(f).update(fs.readFileSync(path.join(outDir, f)));
      fs.writeFileSync(path.join(outDir, 'sw.js'), source(hash.digest('hex').slice(0, 12), ['/', ...files.map((f) => `/${f}`)]));
    },
  };
}
